"""Step 1: download datasets, convert to YOLO format and write an EDA report.

Datasets
  * VisDrone2019-DET (drone / CCTV-style traffic scenes, 10 classes) - the *domain* dataset
    we fine-tune on. Ultralytics' VisDrone recipe downloads it (~2.3 GB) and converts the
    original annotation format to YOLO txt labels.
  * COCO val2017 (5k images) - used only to evaluate the *pretrained* models (baseline),
    so we evaluate on a fixed, seeded 500-image subset to keep it fast.

YOLO label format: one .txt per image, one line per object:
    class_id  cx  cy  w  h        (all normalised to 0..1 by image width/height)

Usage:  python training/prepare_data.py [--skip-coco]
"""
from __future__ import annotations

import argparse
import json
import random
import shutil
import urllib.request
import zipfile
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import yaml  # noqa: E402
from PIL import Image  # noqa: E402

from common import DATASETS, REPORTS, ROOT, VISDRONE_NAMES  # noqa: E402

CFG = ROOT / "training" / "configs"


# --------------------------------------------------------------------------- VisDrone
def prepare_visdrone() -> Path:
    import ultralytics
    from ultralytics.data.utils import check_det_dataset

    src = Path(ultralytics.__file__).parent / "cfg" / "datasets" / "VisDrone.yaml"
    root = (DATASETS / "VisDrone").as_posix()
    out = CFG / "visdrone.yaml"
    if not (DATASETS / "VisDrone" / "labels" / "val").exists():
        # official download + convert recipe, only re-pointed at our datasets/ folder
        text = src.read_text(encoding="utf-8").replace("path: VisDrone ", f"path: {root} ", 1)
        assert f"path: {root}" in text, "Ultralytics VisDrone.yaml format changed"
        out.write_text(text, encoding="utf-8")
        check_det_dataset(str(out), autodownload=True)      # downloads (~2.3 GB) + converts
    # final config without the download script (dataset is now on disk)
    cfg = yaml.safe_load(src.read_text(encoding="utf-8"))
    cfg["path"] = root
    cfg.pop("test", None)                                    # test-dev labels are not used
    cfg.pop("download", None)
    out.write_text("# Generated by training/prepare_data.py\n" + yaml.safe_dump(cfg, sort_keys=False),
                   encoding="utf-8")
    return out


def eda(yaml_path: Path) -> dict:
    """Class balance, objects per image, box-size distribution, image resolutions."""
    cfg = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    root = Path(cfg["path"])
    report: dict = {}
    fig, axes = plt.subplots(2, 2, figsize=(12, 8))
    for split, rel in (("train", cfg["train"]), ("val", cfg["val"])):
        img_dir = root / rel
        lab_dir = Path(str(img_dir).replace("images", "labels"))
        labels = sorted(lab_dir.glob("*.txt"))
        cls_counts: Counter = Counter()
        per_img, areas, sizes = [], [], Counter()
        rng = random.Random(0)
        size_sample = rng.sample(labels, min(300, len(labels)))
        for lf in labels:
            rows = [ln.split() for ln in lf.read_text(encoding="utf-8").splitlines() if ln.strip()]
            per_img.append(len(rows))
            for r in rows:
                cls_counts[int(r[0])] += 1
                areas.append(float(r[3]) * float(r[4]))
        for lf in size_sample:
            for ext in (".jpg", ".png"):
                p = img_dir / (lf.stem + ext)
                if p.exists():
                    with Image.open(p) as im:
                        sizes[f"{im.width}x{im.height}"] += 1
                    break
        # COCO convention (absolute pixels on the original image): small < 32^2, medium < 96^2.
        # Here in relative terms for a typical 1360x765 VisDrone frame.
        a = np.array(areas)
        ref = 1360 * 765
        small = float(np.mean(a * ref < 32 ** 2)) if len(a) else 0
        medium = float(np.mean((a * ref >= 32 ** 2) & (a * ref < 96 ** 2))) if len(a) else 0
        report[split] = {
            "images": len(labels),
            "objects": int(sum(per_img)),
            "objects_per_image": {"mean": round(float(np.mean(per_img)), 1), "max": int(np.max(per_img))},
            "class_counts": {VISDRONE_NAMES[k]: v for k, v in sorted(cls_counts.items())},
            "box_size_fraction": {"small": round(small, 3), "medium": round(medium, 3),
                                  "large": round(1 - small - medium, 3)},
            "common_resolutions": dict(sizes.most_common(5)),
        }
        if split == "train":
            names = [VISDRONE_NAMES[k] for k in sorted(cls_counts)]
            axes[0, 0].bar(names, [cls_counts[k] for k in sorted(cls_counts)], color="#3b7dd8")
            axes[0, 0].set_title("Train: objects per class (class imbalance)")
            axes[0, 0].tick_params(axis="x", rotation=45)
            axes[0, 1].hist(per_img, bins=50, color="#3b7dd8")
            axes[0, 1].set_title("Objects per image")
            axes[1, 0].hist(np.sqrt(a) * 640, bins=60, range=(0, 200), color="#3b7dd8")
            axes[1, 0].set_title("Box size at 640 px input (sqrt(area), px)")
            axes[1, 0].axvline(32 * 640 / 1360, color="r", ls="--", label="COCO 'small' limit")
            axes[1, 0].legend()
    axes[1, 1].axis("off")
    axes[1, 1].text(0, 0.5, json.dumps(report["train"]["box_size_fraction"], indent=1), fontsize=12,
                    family="monospace")
    axes[1, 1].set_title("Train box-size fractions")
    fig.tight_layout()
    fig.savefig(REPORTS / "eda_visdrone.png", dpi=110)
    (REPORTS / "eda_visdrone.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


# --------------------------------------------------------------------------- COCO val subset
COCO_IMAGES = "http://images.cocodataset.org/zips/val2017.zip"
COCO_ANN = "http://images.cocodataset.org/annotations/annotations_trainval2017.zip"


def _download(url: str, dest: Path) -> None:
    if dest.exists():
        return
    print(f"downloading {url}")
    tmp = dest.with_suffix(".part")
    urllib.request.urlretrieve(url, tmp)
    tmp.replace(dest)


def prepare_coco_subset(n: int = 500) -> Path:
    """Fixed random 500-image subset of COCO val2017, in both COCO-json and YOLO format."""
    root = DATASETS / "coco-val500"
    if (root / "annotations.json").exists():
        return root
    raw = DATASETS / "_coco_raw"
    raw.mkdir(exist_ok=True)
    _download(COCO_ANN, raw / "ann.zip")
    _download(COCO_IMAGES, raw / "val2017.zip")
    with zipfile.ZipFile(raw / "ann.zip") as z:
        ann = json.loads(z.read("annotations/instances_val2017.json"))
    rng = random.Random(0)
    imgs = rng.sample(ann["images"], n)
    keep = {im["id"] for im in imgs}
    cats = sorted(c["id"] for c in ann["categories"])
    cat_to_idx = {c: i for i, c in enumerate(cats)}             # COCO's 91 ids -> contiguous 0..79
    (root / "images").mkdir(parents=True, exist_ok=True)
    (root / "labels").mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(raw / "val2017.zip") as z:
        for im in imgs:
            (root / "images" / im["file_name"]).write_bytes(z.read(f"val2017/{im['file_name']}"))
    by_img: dict[int, list] = {}
    anns = [a for a in ann["annotations"] if a["image_id"] in keep]
    for a in anns:
        by_img.setdefault(a["image_id"], []).append(a)
    for im in imgs:
        lines = []
        for a in by_img.get(im["id"], []):
            if a.get("iscrowd"):
                continue
            x, y, w, h = a["bbox"]
            lines.append(f"{cat_to_idx[a['category_id']]} {(x + w / 2) / im['width']:.6f} "
                         f"{(y + h / 2) / im['height']:.6f} {w / im['width']:.6f} {h / im['height']:.6f}")
        (root / "labels" / (Path(im["file_name"]).stem + ".txt")).write_text("\n".join(lines), encoding="utf-8")
    sub = {"images": imgs, "annotations": anns, "categories": ann["categories"]}
    (root / "annotations.json").write_text(json.dumps(sub), encoding="utf-8")
    names = {cat_to_idx[c["id"]]: c["name"] for c in ann["categories"]}
    yaml.safe_dump({"path": str(root.as_posix()), "train": "images", "val": "images", "names": names},
                   (CFG / "coco-val500.yaml").open("w", encoding="utf-8"), sort_keys=False)
    shutil.rmtree(raw)                                           # free ~1 GB
    return root


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-coco", action="store_true")
    args = ap.parse_args()
    y = prepare_visdrone()
    rep = eda(y)
    print(json.dumps({k: {kk: rep[k][kk] for kk in ("images", "objects", "box_size_fraction")} for k in rep},
                     indent=2))
    if not args.skip_coco:
        print("COCO subset at", prepare_coco_subset())
