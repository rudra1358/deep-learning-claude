"""Generate docs/RESULTS.md from the measured reports - so the numbers in the docs are never typed by hand.

    python scripts/make_results.py
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "training" / "reports"


def pct(v):
    return "—" if v is None else f"{100 * v:.1f}"


def ms(v):
    return "—" if v is None else f"{v:.1f} ms"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    m = json.loads((REP / "metrics.json").read_text(encoding="utf-8"))
    eda = json.loads((REP / "eda_visdrone.json").read_text(encoding="utf-8"))
    md = ["# Results (measured)",
          "",
          "Generated by `scripts/make_results.py` from `training/reports/*.json`. Hardware: laptop RTX 3050 6 GB, "
          "Intel i5-13420H. mAP values are percentages. Latencies are single-image, batch 1, 640 px.",
          ""]

    tr = eda["train"]
    md += ["## 1. Data (VisDrone2019-DET)", "",
           f"* train: {tr['images']} images, {tr['objects']:,} objects ({tr['objects_per_image']['mean']} per image, "
           f"max {tr['objects_per_image']['max']})",
           f"* val: {eda['val']['images']} images, {eda['val']['objects']:,} objects",
           f"* box sizes (train): small {pct(tr['box_size_fraction']['small'])} %, medium "
           f"{pct(tr['box_size_fraction']['medium'])} %, large {pct(tr['box_size_fraction']['large'])} %",
           "* class counts: " + ", ".join(f"{k} {v:,}" for k, v in tr["class_counts"].items()),
           "", "![EDA](../training/reports/eda_visdrone.png)", ""]

    if cb := m.get("coco_baseline"):
        md += ["## 2. Baseline on COCO (500 fixed val2017 images, pycocotools)", "",
               table(["model", "mAP@.5:.95", "mAP@.5", "AP small", "AP medium", "AP large", "latency (PyTorch, GPU)", "params"],
                     [[k, pct(v["mAP50_95"]), pct(v["mAP50"]), pct(v["AP_small"]), pct(v["AP_medium"]),
                       pct(v["AP_large"]), ms(v["latency_ms"]), f"{v['params_M']} M"] for k, v in cb.items()]), ""]

    if dg := m.get("domain_gap"):
        ft = m.get("finetuned", {})
        rows = []
        for size in ("yolo11n", "yolo11s"):
            before = dg.get(f"{size}-coco-on-visdrone")
            after = ft.get(f"{size}-visdrone", {}).get("shared_classes_for_domain_gap")
            if before:
                rows.append([size, pct(before["mAP50_95"]), pct(after["mAP50_95"]) if after else "—",
                             pct(before["AP_small"]), pct(after["AP_small"]) if after else "—"])
        md += ["## 3. Domain gap: before vs after fine-tuning", "",
               "VisDrone val, scored only on classes COCO also has (person, bicycle, car, truck, bus, motorcycle; "
               "pedestrian + people merged into person), same images and evaluator before and after.", "",
               table(["model", "mAP@.5:.95 COCO weights", "mAP@.5:.95 fine-tuned", "AP small before", "AP small after"], rows), ""]

    if ft := m.get("finetuned"):
        md += ["## 4. Fine-tuned models on VisDrone val (all 10 classes)", "",
               table(["model", "mAP@.5:.95", "mAP@.5", "precision", "recall", "AP small", "AP medium", "AP large"],
                     [[k, pct(v["mAP50_95"]), pct(v["mAP50"]), pct(v["precision"]), pct(v["recall"]),
                       pct(v["by_size"]["AP_small"]), pct(v["by_size"]["AP_medium"]), pct(v["by_size"]["AP_large"])]
                      for k, v in ft.items()]), "",
               "mAP / precision / recall come from Ultralytics' validator; the AP-by-size columns come from "
               "pycocotools on the same predictions. The two evaluators differ slightly (precision-recall "
               "interpolation, max 300 vs 100 detections per image), so pycocotools' overall mAP is ~1 point "
               "lower — compare numbers only within one evaluator.", "",
               "### Per-class AP@.5:.95", ""]
        names = list(next(iter(ft.values()))["per_class_AP50_95"])
        md += [table(["class"] + list(ft), [[n] + [pct(v["per_class_AP50_95"][n]) for v in ft.values()] for n in names]), ""]
        # training/runs/ is git-ignored, so copy the plots worth showing into docs/img/
        img = ROOT / "docs" / "img"
        img.mkdir(exist_ok=True)
        for k, v in ft.items():
            src_dir = (ROOT / v["confusion_matrix_png"]).parent
            for name in ("confusion_matrix_normalized.png", "BoxPR_curve.png"):
                if (src_dir / name).exists():
                    shutil.copy(src_dir / name, img / f"{k}-{name}")
            md += [f"### {k}: normalised confusion matrix and PR curves", "",
                   f"![confusion matrix](img/{k}-confusion_matrix_normalized.png)",
                   f"![PR curves](img/{k}-BoxPR_curve.png)", ""]
        note = REP / "error_analysis.md"          # hand-written reading of the plots above
        if note.exists():
            md += [note.read_text(encoding="utf-8").strip(), ""]

    if mods := m.get("models"):
        md += ["## 5. ONNX export: parity and serving latency", "",
               "Latency = our full serving path (letterbox + ONNX Runtime + NMS) per image. "
               "Parity = boxes from our ONNX pipeline matched (IoU > 0.9, same class) to Ultralytics/PyTorch boxes.", "",
               table(["model", "ONNX MB", "parity match", "mean IoU", "CPU fp32", "CPU int8 (dynamic)", "GPU fp32", "GPU fp16"],
                     [[k, v["onnx_mb"], pct(v["parity"]["match_rate"]), v["parity"]["mean_iou_of_matches"],
                       ms(v["latency_ms"].get("cpu_fp32")), ms(v["latency_ms"].get("cpu_int8")),
                       ms(v["latency_ms"].get("cuda_fp32")), ms(v["latency_ms"].get("cuda_fp16"))]
                      for k, v in mods.items()]), ""]

    e2e = REP / "end_to_end.json"
    if e2e.exists():
        md += ["## 6. End-to-end pipeline (decode → detect → track → analytics)", "", "```json",
               e2e.read_text(encoding="utf-8").strip(), "```", ""]

    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
