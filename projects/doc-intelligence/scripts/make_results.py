"""Generate docs/RESULTS.md from training/reports/metrics.json - numbers are never typed by hand.

    python scripts/make_results.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "training" / "reports"


def table(head, rows):
    out = ["| " + " | ".join(map(str, head)) + " |", "|" + "---|" * len(head)]
    return "\n".join(out + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def pct(v):
    return "—" if v is None else f"{100 * v:.1f}"


def main():
    m = json.loads((REP / "metrics.json").read_text(encoding="utf-8"))
    md = ["# Results (measured)", "",
          "Generated by `scripts/make_results.py` from `training/reports/metrics.json`. Hardware: laptop "
          "RTX 3050 6 GB, Intel i5-13420H. Evaluation corpus: the 35 Wikipedia articles of SQuAD 2.0 dev, "
          "rendered to PDF (`training/build_eval_corpus.py`) and indexed together, as a user would upload them.", ""]

    r = m.get("retrieval", {})
    if c := r.get("comparison_256"):
        names = {"bm25": "BM25 (keywords)", "dense-minilm": "Dense: MiniLM-L6", "dense-bge": "Dense: BGE-small",
                 "hybrid": "Hybrid: BM25 + BGE (RRF)", "hybrid+rerank": "Hybrid + cross-encoder re-rank"}
        md += ["## 1. Retrieval (answerable questions; relevant = chunk from the right article containing the answer)", "",
               f"{c['chunks']} chunks of ≤ 256 tokens. Recall@k = question has a relevant chunk in the top k; "
               "MRR@10 = mean of 1/rank of the first relevant chunk.", "",
               table(["method", "Recall@1", "Recall@5", "Recall@10", "Recall@20", "MRR@10", "ms / query"],
                     [[names[k], pct(v["recall@1"]), pct(v["recall@5"]), pct(v["recall@10"]), pct(v["recall@20"]),
                       f"{v['mrr@10']:.3f}", v["ms_per_query"]]
                      for k, v in c.items() if k in names]), ""]
    if s := r.get("chunk_size_sweep"):
        md += ["### Chunk size (hybrid retrieval)", "",
               table(["max tokens", "chunks", "Recall@1", "Recall@5", "Recall@10", "MRR@10"],
                     [[k, v["chunks"], pct(v["recall@1"]), pct(v["recall@5"]), pct(v["recall@10"]), f"{v['mrr@10']:.3f}"]
                      for k, v in s.items()]), "",
               "Recall@k is not perfectly comparable across sizes (bigger chunks contain more text, so a hit is "
               "easier but less precise, and the reader then has to search a longer passage).", ""]

    if q := m.get("qa", {}).get("squad2"):
        md += ["## 2. Question answering (SQuAD 2.0 dev, answerable + unanswerable)", "",
               f"{q['questions']} seeded questions ({q['answerable']} answerable). The no-answer margin is tuned on "
               f"the first {q['tune_split']} and **reported on the other {q['report_split']}**. Official SQuAD EM/F1 "
               "(an unanswerable question counts as correct only if the system answers nothing).", ""]
        rows = []
        for setting, label in (("oracle", "Reader only (gold paragraph given)"),
                               ("system", "Full system (retrieve from all 35 PDFs → re-rank → read top 5)")):
            v = q[setting]
            for variant, vl in (("tuned_on_first_half_reported_on_second", f"tuned margin {v['no_answer_margin']:+.2f}"),
                                ("margin_0_reported_on_second", "margin 0"),
                                ("always_answer_reported_on_second", "always answer")):
                e = v[variant]
                rows.append([label, vl, e["EM"], e["F1"], e["F1_answerable"], e["accuracy_unanswerable"]])
            rows.append([label, "latency", f"{v['ms_per_question']} ms / question", "", "", ""])
        md += [table(["setting", "no-answer rule", "EM", "F1", "F1 (answerable)", "correct 'no answer' (unanswerable)"], rows), ""]

    if gen := m.get("generation"):
        names = {"prompt_v1": "v1: instructions only", "prompt_v2": "v2: rules + 2 worked examples",
                 "prompt_v2+reader_gate": "v2 + reader gate (skip LLM if the reader finds no answer)"}
        rows = []
        for k, label in names.items():
            if g := gen.get(k):
                a, u = g["answerable"], g["unanswerable"]
                rows.append([label, a["answer_contains_gold"], a["cited_at_least_one_source"], a["wrongly_refused"],
                             u["refused_correctly"], u["hallucination_rate"], g["ms_per_question"]])
        any_g = next(iter(gen.values()))
        md += ["## 3. Generative answers (Qwen2.5-1.5B-Instruct, RAG over the same index)", "",
               f"Same {any_g['questions']} questions (half answerable, half unanswerable), same retrieved top-5 "
               "context for every variant, greedy decoding. Percentages.", "",
               table(["variant", "answerable: contains gold", "answerable: cites a source", "answerable: wrongly refused",
                      "unanswerable: correctly refused", "unanswerable: hallucinated", "ms / question"], rows), ""]

    if n := m.get("ner", {}).get("distilbert-conll2003"):
        md += ["## 4. Named-entity recognition (our fine-tuned DistilBERT, CoNLL-2003 test)", "",
               f"Entity-level F1 (seqeval): **{100 * n['test_f1']:.1f}** on {n['test_sentences']} test sentences "
               f"after training on {n['train_sentences']}.", "",
               table(["type", "precision", "recall", "F1", "support"],
                     [[k, pct(v["precision"]), pct(v["recall"]), pct(v["f1-score"]), int(v["support"])]
                      for k, v in n["per_type"].items()]), "",
               table(["epoch", "train loss", "test F1", "minutes"],
                     [[h["epoch"], h["train_loss"], pct(h["test_f1"]), h["minutes"]] for h in n["history"]]), ""]

    if c := m.get("classifier", {}).get("distilbert-agnews"):
        labels = c["labels"]
        md += ["## 5. Topic classification (our fine-tuned DistilBERT, AG News test)", "",
               f"Accuracy **{pct(c['test_accuracy'])} %**, macro-F1 **{pct(c['test_macro_f1'])}** on {c['test_size']} "
               f"test articles (trained on {c['train_size']}).", "",
               "Confusion matrix (rows = true class, columns = predicted):", "",
               table([""] + labels, [[lb] + row for lb, row in zip(labels, c["confusion_matrix"])]), ""]

    if s := m.get("summarization", {}).get("cnn_dailymail"):
        d, l3 = s["distilbart"], s["lead3_baseline"]
        md += ["## 6. Summarisation (DistilBART-CNN, CNN/DailyMail test)", "",
               table(["system", "ROUGE-1", "ROUGE-2", "ROUGE-Lsum"],
                     [["DistilBART (abstractive)", d["rouge1"], d["rouge2"], d["rougeLsum"]],
                      ["LEAD-3 baseline (first 3 sentences)", l3["rouge1"], l3["rouge2"], l3["rougeLsum"]]]), "",
               f"{s['articles']} articles, {d['ms_per_article']} ms per article on the GPU.", ""]

    note = REP / "analysis.md"
    if note.exists():
        md += [note.read_text(encoding="utf-8").strip(), ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
